param([Parameter(Mandatory=$true)][string]$Version)
$ErrorActionPreference = 'Stop'
if ($Version -notmatch '^\d+\.\d+\.\d+(-[0-9A-Za-z]+([.-][0-9A-Za-z]+)*)?$') { throw 'Use a semantic version such as 1.24.1 or 1.24.1-beta.1.' }
$env:Wao_RELEASE_VERSION = $Version
Push-Location (Split-Path -Parent $PSScriptRoot)
try {
  node -e "const fs=require('fs');for(const file of ['release/app/package.json','release/app/package-lock.json']){const data=JSON.parse(fs.readFileSync(file,'utf8'));data.version=process.env.Wao_RELEASE_VERSION;if(data.packages?.[''])data.packages[''].version=data.version;fs.writeFileSync(file,JSON.stringify(data,null,2)+'\n')}"
  if ($LASTEXITCODE -ne 0) { throw 'Version update failed.' }
  # src/renderer/buildInfo.ts is gitignored (local stamps rewrite it constantly),
  # so a fresh CI checkout has none and about.tsx's import breaks tsc. Generate
  # the About-box stamp here: the Actions run number is this build's identity on
  # GitHub, and local builds overwrite it afterwards via the stamp probe anyway.
  $runNumber = if ($env:GITHUB_RUN_NUMBER) { $env:GITHUB_RUN_NUMBER } else { '0' }
  $hash = (git rev-parse --short HEAD) 2>$null
  if (-not $hash) { $hash = 'unknown' }
  $at = (Get-Date).ToString('ddd MM/dd/yyyy HH:mm', [Globalization.CultureInfo]::InvariantCulture)
  $info = "// Generated by scripts/Set-WaoReleaseVersion.ps1 (or the local stamp probe); do not edit.`r`nexport const BUILD_INFO = { n: $runNumber, at: `"$at`", hash: `"$hash`" }`r`n"
  [IO.File]::WriteAllText((Join-Path (Get-Location) 'src/renderer/buildInfo.ts'), $info)
} finally { Pop-Location; Remove-Item Env:Wao_RELEASE_VERSION }
