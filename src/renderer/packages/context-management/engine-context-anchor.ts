import { useEffect, useState } from 'react'
import { getMessageText } from '@shared/utils/message'
import type { Message } from '@shared/types'
import { rendererApplication } from '@/app/renderer-application'
import { estimateTokensForTokenizerType } from '@shared/token-estimation/tokenizer'
import { getTokenizerType, type TokenModel } from '../token'

// Why this exists: every UI token number is a cl100k_base estimate, but a
// Qwen/Strata engine counts the same text with its own BPE, roughly 15-20%
// tighter. On big contexts the estimate reads ~100% while the engine sits at
// ~85%, and automatic compaction then summarizes a conversation that still
// had real headroom. The engine's exact prompt size is already stored on each
// assistant reply (usage.inputTokens = the real prompt of that request), so
// the current context can be anchored to that exact number and only the small
// tail after it estimated.

/** The last assistant reply whose usage records the engine's exact prompt size. */
export function findEngineContextAnchor(
  messages: readonly Message[],
  modelId?: string
): { index: number; message: Message; inputTokens: number } | null {
  for (let i = messages.length - 1; i >= 0; i--) {
    const message = messages[i]
    if (message.role !== 'assistant') continue
    if (message.generating || message.error) continue
    // A reply generated by a different model measured a different tokenizer;
    // it calibrates nothing for this one.
    if (modelId && message.modelId && message.modelId !== modelId) continue
    // lastStepInputTokens is the final step's prompt: exactly the context the
    // engine saw. inputTokens alone is only equal for single-step replies;
    // for Work Mode replies it sums the whole agent loop (up to 10x), which
    // older messages store (field: 4.13M stored vs 377K measured) - the
    // window-cap guard in calibrateContextTokens still rejects those.
    const measured = message.usage?.lastStepInputTokens ?? message.usage?.inputTokens
    if (typeof measured !== 'number' || !Number.isFinite(measured) || measured <= 0) continue
    return { index: i, message, inputTokens: measured }
  }
  return null
}

/**
 * Engine-anchored context size for the NEXT request: the exact prompt the
 * engine last measured, plus the estimate for everything appended since
 * (that reply's own text, later turns, the pending draft). The anchor already
 * includes the system prompt and request overhead, so none is added here.
 * The small tail is still cl100k-estimated, so the result stays approximate
 * but tracks the engine's units instead of overshooting the whole history by
 * the tokenizer mismatch.
 */
export function calibrateContextTokens(params: {
  messages: readonly Message[]
  model?: TokenModel
  /** Exact engine prompt size of the anchor; null falls back to the estimate. */
  anchor: { index: number; inputTokens: number } | null
  /** Cl100k estimate of the full context the caller already computed. */
  estimatedTokens: number
  /** Draft not present in `messages`; counted into the tail when given. */
  pendingTokens?: number
}): { tokens: number; calibrated: boolean } {
  const { messages, model, anchor, estimatedTokens, pendingTokens = 0 } = params
  if (!anchor) return { tokens: estimatedTokens, calibrated: false }
  const type = getTokenizerType(model)
  let tail = 0
  for (let i = anchor.index; i < messages.length; i++) {
    // From the anchor reply itself onward: its text was not in its own prompt.
    tail += estimateTokensForTokenizerType(getMessageText(messages[i], false), type) + 4
  }
  const tokens = anchor.inputTokens + tail + pendingTokens
  // A stale or mismatched measurement must never hide an overflow: the
  // anchor's own size is the hard floor.
  const anchored = Math.max(tokens, anchor.inputTokens)
  // Cumulative-vs-real discrimination. An engine measurement can legitimately
  // exceed the configured window (Work Mode tool overhead, or the engine
  // sliding a slightly larger prompt), so "above window" is NOT proof of a
  // running total - at a 524K window that rejected honest 521K prompts and
  // the badge fell back to the estimate (field complaint). The reliable tell
  // is ratio to the caller's own estimate of the same history: tokenizer
  // disagreement is at most ~1.5x (cl100k vs Qwen BPE), while session-
  // cumulative usage (the AI SDK summing agent-loop steps) is 2x and up
  // (field: 757K=2x, 4.13M=10x). Accept real measurements, reject sums.
  if (anchor.inputTokens > estimatedTokens * 1.5) return { tokens: estimatedTokens, calibrated: false }
  return { tokens: anchored, calibrated: true }
}

/**
 * Reactive engine-anchored total for the token badge: reloads the transcript
 * tail whenever the session revision changes and recalibrates each fresh
 * estimate against the anchor. Falls back to the raw estimate when no anchor
 * exists or the read fails.
 */
export function useEngineCalibratedContextTokens(params: {
  sessionId: string | null
  revision?: number
  model?: TokenModel
  estimatedTokens: number
  draftTokens: number
}): { totalTokens: number; calibrated: boolean } {
  const { sessionId, revision, model, estimatedTokens, draftTokens } = params
  const [anchorState, setAnchorState] = useState<{
    sessionId: string
    anchor: { index: number; inputTokens: number }
    messages: readonly Message[]
  } | null>(null)
  useEffect(() => {
    let cancelled = false
    if (!sessionId) {
      setAnchorState(null)
      return
    }
    const run = async () => {
      try {
        const page = await rendererApplication.sessions.readSessionTranscriptWindow({
          sessionId,
          limit: 40,
          maxBytes: 2 * 1024 * 1024,
          origin: 'tail' as const,
        })
        if (cancelled) return
        const messages = (page?.messages || []).map((row: { message: Message }) => row.message)
        const anchor = findEngineContextAnchor(messages, model?.modelId)
        setAnchorState(anchor ? { sessionId, anchor, messages } : null)
      } catch {
        if (!cancelled) setAnchorState(null)
      }
    }
    void run()
    // A reply's usage.inputTokens is persisted AFTER its text completes, and
    // the revision bump that retriggers this read can race that write; the
    // badge then anchors on the previous reply and reads below the engine's
    // newest measurement (field: 339K badge vs 344,777 monitor). One delayed
    // re-read lands the fresh measurement.
    const retry = setTimeout(() => void run(), 3000)
    return () => {
      cancelled = true
      clearTimeout(retry)
    }
    // revision re-runs the read so a fresh reply's usage becomes the anchor
  }, [sessionId, revision, model?.modelId])
  if (!sessionId || !anchorState || anchorState.sessionId !== sessionId) {
    return { totalTokens: estimatedTokens, calibrated: false }
  }
  const calibrated = calibrateContextTokens({
    messages: anchorState.messages,
    model,
    anchor: anchorState.anchor,
    estimatedTokens,
    pendingTokens: draftTokens,
  })
  return { totalTokens: calibrated.tokens, calibrated: calibrated.calibrated }
}
